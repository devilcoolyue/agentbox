#!/usr/bin/env python3
"""Generate versioned wire types, not the entire API. No third-party runtime."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def ts_type(schema):
    if not schema:
        return "unknown"
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(value) for value in schema['anyOf'])
    kind = schema['type']
    if kind == 'array':
        return f'Array<{ts_type(schema["items"])}>'
    return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[kind]


def generate(source='chat-errors-v1.schema.json'):
    schema = json.loads((ROOT / 'contracts' / source).read_text())
    lines = ['// Generated by scripts/generate-contracts.py; edit the versioned schema.']
    for name, value in schema['$defs'].items():
        if value.get('type') != 'object':
            lines.append(f'export type {name} = {ts_type(value)};')
            continue
        lines.append(f'export interface {name} {{')
        for key, prop in value['properties'].items():
            optional = '' if key in value['required'] else '?'
            lines.append(f'  {key}{optional}: {ts_type(prop)};')
        lines.append('}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for source, target in [('chat-errors-v1.schema.json', 'v1.d.ts'),
                           ('collaboration-v1.schema.json', 'collaboration-v1.d.ts')]:
        path = ROOT / 'web/src/contracts' / target
        content = generate(source)
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, 'Contract types are stale; run python3 scripts/generate-contracts.py\n')
        else:
            path.write_text(content)
